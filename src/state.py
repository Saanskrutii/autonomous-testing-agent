from typing import TypedDict, Optional

class TestingAgentState(TypedDict):
    repo_path: str                      # Path to target repository
    repo_structure: dict                # AST structure extracted by code_analyzer
    test_plan: list[dict]               # Planned test cases from LLM
    generated_test_code: str            # Pytest code string generated by LLM
    test_file_path: str                 # File path where pytest code is saved on disk
    test_output: str                    # Raw terminal output from running pytest
    pass_rate: float                    # Test pass percentage (0.0 - 100.0)
    failed_tests: list[dict]            # List of failed test details & error tracebacks
    coverage_percentage: float          # Test coverage percentage
    iteration: int                      # Iteration counter for retry loop
    status: str                         # Status message (e.g. 'analyzed', 'tested', 'completed')
